// Invoices → subscriptions (per Isaac, Oct 14). Ported verbatim from
// netlify/lib/invoice-map.js (CommonJS → ES module, nothing else changed).
//
// RevHawk's FieldRoutesTicket mirror never fills fieldRoutes_subscriptionID
// (0 of 418k tickets this year), so anything that filtered tickets by
// subscription id found none — the add-on streak and any "paid invoices" rule
// saw zero invoices.
//
// A ticket belongs to a subscription when:
//   1. it is an appointment ticket and that appointment's subscriptionID is
//      the subscription (FieldRoutesAppointment carries it), or
//   2. it is a billing ticket (RECURRING / INITIAL, no appointment) and the
//      customer has exactly ONE subscription with the ticket's serviceID —
//      true for ~97% of recurring invoices (Sep–Oct 2026). Ambiguous ones
//      (same service twice on one customer) are left out, never guessed.
// Paid = total > 0, balance ≤ 0, ticket not voided (active 0 / -1).
//
// Why the SQL is built in JS and not a .sql file: it takes a LIST of
// subscription ids, and config/bigquery.js named parameters are scalars only.
// The id list is sanitised to [0-9A-Za-z_-] before it is inlined, exactly as
// the Netlify version did.

const q = (ids) => ids.map(x => "'" + String(x).replace(/[^0-9A-Za-z_-]/g, '') + "'").join(',');

// SQL returning one row per ticket mapped to a wanted subscription:
// sub_id, ticket_id, cid, invoice_date, active, total, balance, paid_at, kind
export function ticketsForSubsSql(T, subIds, since) {
  const sinceSql = /^\d{4}-\d{2}-\d{2}$/.test(String(since || '')) ? "'" + since + "'" : "'2000-01-01'";
  return `
WITH subLatest AS (
  SELECT fieldRoutes_subscriptionID AS sid, fieldRoutes_customerID AS cid, fieldRoutes_serviceID AS sv
  FROM ${T('FieldRoutesSubscription')}
  WHERE fieldRoutes_customerID IN (SELECT DISTINCT fieldRoutes_customerID FROM ${T('FieldRoutesSubscription')} WHERE fieldRoutes_subscriptionID IN (${q(subIds)}))
  QUALIFY ROW_NUMBER() OVER (PARTITION BY fieldRoutes_subscriptionID ORDER BY fieldRoutes_dateUpdated DESC, updatedAt DESC) = 1
),
want AS (SELECT * FROM subLatest WHERE sid IN (${q(subIds)})),
amb AS (SELECT cid, sv, COUNT(DISTINCT sid) AS k FROM subLatest GROUP BY 1, 2),
tk AS (
  SELECT * FROM ${T('FieldRoutesTicket')}
  WHERE fieldRoutes_customerID IN (SELECT cid FROM want) AND LEFT(fieldRoutes_invoiceDate, 10) >= ${sinceSql} AND fieldRoutes_templateType = 'NA'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY fieldRoutes_ticketID ORDER BY updatedAt DESC) = 1
),
ap AS (
  SELECT fieldRoutes_appointmentID AS aid, ANY_VALUE(fieldRoutes_subscriptionID) AS sid
  FROM ${T('FieldRoutesAppointment')}
  WHERE fieldRoutes_appointmentID IN (SELECT fieldRoutes_appointmentID FROM tk WHERE fieldRoutes_appointmentID NOT IN ('', '0'))
  GROUP BY 1
),
mapped AS (
  SELECT tk.*, CASE
      WHEN ap.sid IS NOT NULL AND ap.sid NOT IN ('', '0') THEN ap.sid
      WHEN (tk.fieldRoutes_appointmentID IS NULL OR tk.fieldRoutes_appointmentID IN ('', '0')) AND amb.k = 1 THEN w.sid
    END AS sub_id
  FROM tk
  LEFT JOIN ap ON ap.aid = tk.fieldRoutes_appointmentID
  LEFT JOIN want w ON w.cid = tk.fieldRoutes_customerID AND w.sv = tk.fieldRoutes_serviceID
  LEFT JOIN amb ON amb.cid = tk.fieldRoutes_customerID AND amb.sv = tk.fieldRoutes_serviceID
)
SELECT m.sub_id, m.fieldRoutes_ticketID AS ticket_id, m.fieldRoutes_customerID AS cid,
       LEFT(m.fieldRoutes_invoiceDate, 10) AS invoice_date, m.fieldRoutes_active AS active,
       SAFE_CAST(m.fieldRoutes_total AS FLOAT64) AS total, SAFE_CAST(m.fieldRoutes_balance AS FLOAT64) AS balance,
       m.fieldRoutes_autoGeneratedType AS kind,
       (SELECT MAX(LEFT(p.fieldRoutes_dateApplied, 10)) FROM ${T('FieldRoutesAppliedPayment')} p WHERE p.fieldRoutes_ticketID = m.fieldRoutes_ticketID) AS paid_at
FROM mapped m
WHERE m.sub_id IN (SELECT sid FROM want)`;
}
export const isVoid = (t) => String(t.active) === '0' || String(t.active) === '-1';
export const isPaid = (t) => !isVoid(t) && (Number(t.total) || 0) > 0 && (Number(t.balance) || 0) <= 0.005;
// Paid invoices on a subscription dated on/after `from` (the sale date — the initial's invoice counts, per Isaac).
export function paidCountFrom(tickets, from) {
  const f = String(from || '').slice(0, 10);
  return (tickets || []).filter(t => isPaid(t) && (!f || String(t.invoice_date || '') >= f)).length;
}
