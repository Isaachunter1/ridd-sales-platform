// The cron table lives in the code, next to each job. This script reads every
// job's `schedule` and writes server/infra/scheduler.yaml + the exact gcloud
// commands that create or update the Cloud Scheduler entries.
//
//   npm run schedules --workspace server                 → writes infra/scheduler.yaml + infra/scheduler.sh
//   npm run schedules --workspace server -- --apply      → also runs the gcloud commands
//
// Needs: SERVICE_URL (the Cloud Run URL), GCP_PROJECT, GCP_REGION, and the
// API_TOKEN value in Secret Manager (the script references it, never prints it).
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { createApp } from '../index.js';   // boots the job list; never connects to anything

const here = path.dirname(fileURLToPath(import.meta.url));
const app = await createApp();
const jobs = app.locals.jobs.filter(j => j.schedule);

const SERVICE_URL = process.env.SERVICE_URL || 'https://<SERVICE_URL>';
const PROJECT = process.env.GCP_PROJECT || '<GCP_PROJECT>';
const REGION = process.env.GCP_REGION || 'us-central1';
const TZ = process.env.SCHEDULE_TZ || 'Etc/UTC';   // Netlify crons were UTC — carried over as-is. A job can set its own tz: job(name, { schedule, tz: 'America/New_York' })

const yaml = ['# GENERATED by server/scripts/schedules.js — edit the job files, not this.', 'jobs:'];
const sh = ['#!/usr/bin/env bash', '# GENERATED by server/scripts/schedules.js — safe to re-run; "update" is tried first, "create" on a miss.', 'set -euo pipefail',
  `PROJECT=${PROJECT}`, `REGION=${REGION}`, `URL=${SERVICE_URL}`, 'TOKEN="$(gcloud secrets versions access latest --secret=API_TOKEN --project="$PROJECT")"', ''];
for (const j of jobs) {
  yaml.push(`  - name: ridd-${j.name}`, `    schedule: "${j.schedule}"`, `    timeZone: ${j.tz || TZ}`, `    uri: ${SERVICE_URL}/jobs/${j.name}`, `    attemptDeadline: ${Math.min(j.timeoutMinutes, 30) * 60}s`, `    description: "${(j.description || '').replace(/"/g, "'")}"`);
  const common = `--project="$PROJECT" --location="$REGION" --schedule="${j.schedule}" --time-zone="${j.tz || TZ}" --uri="$URL/jobs/${j.name}" --http-method=POST --headers="X-API-TOKEN=$TOKEN" --attempt-deadline=${Math.min(j.timeoutMinutes, 30) * 60}s --description="${(j.description || '').replace(/"/g, "'")}"`;
  sh.push(`gcloud scheduler jobs update http ridd-${j.name} ${common} 2>/dev/null || gcloud scheduler jobs create http ridd-${j.name} ${common}`);
}
const infra = path.join(here, '..', 'infra');
fs.mkdirSync(infra, { recursive: true });
fs.writeFileSync(path.join(infra, 'scheduler.yaml'), yaml.join('\n') + '\n');
fs.writeFileSync(path.join(infra, 'scheduler.sh'), sh.join('\n') + '\n', { mode: 0o755 });
console.log('wrote infra/scheduler.yaml and infra/scheduler.sh for ' + jobs.length + ' job(s): ' + jobs.map(j => j.name + ' (' + j.schedule + ')').join(', '));
if (process.argv.includes('--apply')) {
  if (SERVICE_URL.includes('<')) { console.error('set SERVICE_URL and GCP_PROJECT before --apply'); process.exit(2); }
  execSync('bash ' + path.join(infra, 'scheduler.sh'), { stdio: 'inherit' });
}
process.exit(0);
