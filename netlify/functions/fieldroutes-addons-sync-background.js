// ── FieldRoutes ticket items → add_ons (per Isaac + COO, Sep 2026) ──────────
// SKELETON. RIDD is moving to < 25 service types with everything else sold
// as an ADD-ON: a ticket item on the invoice, credited (per line) to the
// employee who sold it. RevHawk does not mirror ticket items
// (FieldRoutesTicket.fieldRoutes_items is empty on every row), so this
// worker asks the FieldRoutes API directly — the same way the live pull
// asks for subscriptions — and writes one add_ons row per
// (subscription, add-on service), folding the initial and recurring
// charges of the same add-on into one row (netlify/lib/add-on-streak.js).
//
// With app_settings.autolog.upsells === 'auto' it also creates the `sales`
// upsell row (netlify/lib/upsell-record.js) so the Technicians / Office
// Sales tabs show the add-on the same day; with 'manual' it only records the
// add-on (the Log Sale form stays).
//
// Runs every 15 min in selling hours (addons-scheduled.js). Idempotent: the
// unique (subscription_id, service_name) key and sales.crm_ticket_id dedupe.
//
// TODO(Isaac) before this goes live — confirm against the dummy account
// [68003] / sub 193894 recurring ticket:
//   • ticketItem endpoints: assumed `ticketItem/search` (dateCreated ≥ from,
//     returns ticketItemIDs) and `ticketItem/get` (ticketItemIDs → items).
//   • item field names read in add-on-streak.js normalizeItem(): ticketItemID,
//     ticketID, description, total, employeeID (credit-to), dateCreated.
//   • which ticket field marks the initial ticket (autoGeneratedType / templateType).
//
// Env: FIELDROUTES_SUBDOMAIN / FIELDROUTES_AUTH_KEY / FIELDROUTES_AUTH_TOKEN,
//      SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY. Silently skips without them.

const { createClient } = require('@supabase/supabase-js');
const { applyFieldRoutesEnv, fieldRoutesBase } = require('../lib/integrations.js');
const { requireSyncSecret } = require('../lib/sync-gate.js');
const { makeIsAddOn, upsellSaleRow } = require('../lib/upsell-record.js');
const { groupTicketItems } = require('../lib/add-on-streak.js');

function frBase() { return fieldRoutesBase(); }
async function fr(endpoint, params) {
  const q = new URLSearchParams({ authenticationKey: process.env.FIELDROUTES_AUTH_KEY || '', authenticationToken: process.env.FIELDROUTES_AUTH_TOKEN || '' });
  for (const [k, v] of Object.entries(params || {})) q.set(k, typeof v === 'string' ? v : JSON.stringify(v));
  let res, txt;
  for (let attempt = 0; ; attempt++) {
    res = await fetch(frBase() + endpoint + '?' + q.toString()); txt = await res.text();
    const limited = res.status === 429 || /too many requests|rate limit/i.test(txt.slice(0, 300));
    if (!limited || attempt >= 2) break;
    await new Promise(r => setTimeout(r, 1500 * (attempt + 1)));
  }
  let json; try { json = JSON.parse(txt); } catch (e) { throw new Error(endpoint + ': non-JSON (' + res.status + '): ' + txt.slice(0, 120)); }
  if (json.success === false || (json.errorMessage && json.errorMessage !== '')) throw new Error(endpoint + ': ' + (json.errorMessage || 'request failed'));
  return json;
}
const chunk = (arr, n) => { const out = []; for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n)); return out; };
const listOf = (got, key) => Array.isArray(got[key]) ? got[key] : Object.values(got[key] || {});
const ROLE_OF_TYPE = { '0': 'office_staff', '1': 'technician', '2': 'sales_rep' };

exports.handler = async (event) => {
  const started = Date.now();
  const _gate = requireSyncSecret(event); if (_gate) return _gate;
  const SUPABASE_URL = process.env.SUPABASE_URL, SERVICE_ROLE = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!SUPABASE_URL || !SERVICE_ROLE) return { statusCode: 500, body: 'SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY required' };
  // Credentials come from Settings → Data sources (public.integrations) first, Netlify env as the fallback.
  try { await applyFieldRoutesEnv(createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } })); } catch (e) { /* env fallback */ }
  if (!frBase() || !process.env.FIELDROUTES_AUTH_KEY || !process.env.FIELDROUTES_AUTH_TOKEN) return { statusCode: 200, body: 'fieldroutes env not set — skipped' };
  const supabase = createClient(SUPABASE_URL, SERVICE_ROLE, { auth: { persistSession: false } });
  const log = { items: 0, addOns: 0, inserted: 0, updated: 0, sales: 0, unmatchedEmployees: 0 };
  try {
    const { data: alRow } = await supabase.from('app_settings').select('value').eq('key', 'autolog').maybeSingle();
    const AL = Object.assign({ enabled: false, start: '2026-01-01', upsells: 'manual', upsell_services: [], addons_lookback_days: 3 }, (alRow && alRow.value) || {});
    if (!AL.enabled) return { statusCode: 200, body: 'autolog disabled — skipped' };
    // Which recurring-ticket lines are add-ons: the admin's configured terms
    // when set, otherwise every line EXCEPT fees / discounts / tax (per the
    // 68003 dry run, Sep 29: Service Fee $4.87 rides every ticket and is not
    // an add-on; Mosquito Seasonal and Rodent are).
    const NOT_ADDON = /^(service fee|tax|nsf fee|late fee|finance charge|credit card fee)\b|discount/i;
    const isAddOn = (Array.isArray(AL.upsell_services) && AL.upsell_services.length) ? makeIsAddOn(AL.upsell_services) : (name) => !NOT_ADDON.test(String(name || '').trim());
    const lookback = Math.max(1, Number(AL.addons_lookback_days) || 3);
    const since = new Date(Date.now() - lookback * 86400000).toISOString().slice(0, 10);
    const from = since > String(AL.start).slice(0, 10) ? since : String(AL.start).slice(0, 10);
    // Full sweep (nightly, ?full=1): every active subscription, so removed
    // items and cancelled subscriptions are caught. Otherwise only
    // subscriptions FieldRoutes touched since `from` (adding a line to the
    // recurring ticket bumps the subscription's dateUpdated — 68003, 9/22).
    const full = !!(event && event.queryStringParameters && event.queryStringParameters.full);
    log.mode = full ? 'full' : 'recent';

    // 1. Active subscriptions → their recurring (template) tickets.
    const sq = full ? { active: 1 } : { active: 1, dateUpdated: { operator: '>=', value: from } };
    const subIds = ((await fr('subscription/search', sq)).subscriptionIDs || []).map(String);
    const subs = {};
    for (const part of chunk(subIds, 1000)) { const got = await fr('subscription/get', { subscriptionIDs: part.map(Number) }); listOf(got, 'subscriptions').forEach(x => { subs[String(x.subscriptionID)] = x; }); }
    // 2. subscription/get EMBEDS the recurring ticket, line items included
    //    (68003 dry run, Sep 29) — read it straight off the subscription.
    //    Only a sub that carries a bare ticket id falls back to ticket/get
    //    (ticketItem/search returns nothing for template tickets).
    const recOf = (x) => { const rt = x.recurringTicket; return rt && typeof rt === 'object' ? String(rt.ticketID || '') : String(rt || ''); };
    const tickets = {}; const items = []; const needGet = [];
    const take = (t) => {
      tickets[String(t.ticketID)] = t;
      const its = Array.isArray(t.items) ? t.items : Object.values(t.items || {});
      its.forEach(it => items.push({ ...it, ticketID: t.ticketID, customerID: t.customerID, subscriptionID: t.subscriptionID, officeID: it.officeID || t.officeID }));
    };
    for (const x of Object.values(subs)) {
      const rt = x.recurringTicket;
      if (rt && typeof rt === 'object') take({ ...rt, subscriptionID: rt.subscriptionID || x.subscriptionID, customerID: rt.customerID || x.customerID });
      else if (rt && String(rt) !== '0') needGet.push(String(rt));
    }
    for (const part of chunk(needGet, 1000)) { const got = await fr('ticket/get', { ticketIDs: part.map(Number) }); listOf(got, 'tickets').forEach(take); }
    const recIds = Object.keys(tickets);
    log.subscriptions = Object.keys(subs).length; log.tickets = recIds.length; log.items = items.length;

    // 3. Fold into add-ons (one per subscription + add-on name).
    const addOns = groupTicketItems(items, { isAddOn, tickets });
    for (const a of addOns) {
      const sub = subs[a.subscription_id] || {};
      a.base_service = sub.serviceType || sub.serviceDescription || null;
      a.recurring_ticket_id = recOf(sub) || null;
    }
    log.addOns = addOns.length;

    // 4. Resolve the credited employee → app profile (any of a person's branch ids).
    const [rosterQ, profQ, offQ, svcQ] = await Promise.all([
      supabase.from('fieldroutes_employees').select('employee_id, employee_ids, type_label, type'),
      supabase.from('profiles').select('id, fieldroutes_employee_id, office_id').not('fieldroutes_employee_id', 'is', null),
      supabase.from('offices').select('id, name'),
      supabase.from('service_types').select('id, name'),
    ]);
    const profByEmp = new Map(); const typeOfEmp = new Map();
    (profQ.data || []).forEach(p => profByEmp.set(String(p.fieldroutes_employee_id).trim(), p));
    (rosterQ.data || []).forEach(e => {
      const all = String(e.employee_ids || e.employee_id || '').split(',').map(x => x.trim()).filter(Boolean);
      const hit = all.map(id => profByEmp.get(id)).find(Boolean);
      all.forEach(id => { if (hit && !profByEmp.has(id)) profByEmp.set(id, hit); typeOfEmp.set(id, e.type_label || e.type || null); });
    });
    // FieldRoutes officeID → app office id, by name (same as the live pull).
    const officeByFr = new Map(); const officeByName = new Map((offQ.data || []).map(o => [String(o.name || '').trim().toLowerCase(), o.id]));
    try { const got = await fr('office/get', {}); listOf(got, 'offices').forEach(o => { const id = officeByName.get(String(o.officeName || '').trim().toLowerCase()); if (id) officeByFr.set(String(o.officeID), id); }); } catch (e) { console.warn('[fr-addons] office lookup skipped:', e.message); }
    const svcByName = new Map((svcQ.data || []).map(s => [String(s.name || '').trim().toLowerCase(), s.id]));

    // 6b. Revenue credit by account: split each subscription's contract
    //     value into base plan / fees / add-ons (per Isaac, Sep 29).
    //     services after the initial n = round((CV − initial charge) ÷ recurring
    //     subtotal); whatever the initial ticket carries beyond its charge is
    //     fees. Ties to FieldRoutes exactly on 68003 ($1,246.44 = 638 base +
    //     58.44 fees + 330 Mosquito + 220 Rodent).
    const nowIso = new Date().toISOString();
    const money2 = (x) => Math.round((Number(x) || 0) * 100) / 100;
    const revRows = [];
    for (const x of Object.values(subs)) {
      const rt = x.recurringTicket && typeof x.recurringTicket === 'object' ? x.recurringTicket : tickets[recOf(x)];
      if (!rt) continue;
      const cv = money2(x.contractValue), init = money2(x.initialServiceTotal ?? x.initialQuote);
      const recSub = money2(rt.subTotal ?? x.recurringCharge), baseCharge = money2(rt.serviceCharge);
      if (!(cv > 0) || !(recSub > 0)) continue;
      const n = Math.max(0, Math.round((cv - init) / recSub));
      const initExtra = money2(cv - init - n * recSub);
      const soldBy = String(x.soldBy || '').trim();
      const soldProf = soldBy ? profByEmp.get(soldBy) : null;
      const lines = [{ name: x.serviceType || 'Base plan', kind: 'base', per_service: baseCharge, value: money2(init + baseCharge * n), credited_employee_id: soldBy || null, credited_profile_id: soldProf ? soldProf.id : null }];
      const its = Array.isArray(rt.items) ? rt.items : Object.values(rt.items || {});
      let feeSeen = false;
      for (const it of its) {
        const name = String(it.description || '').trim(); const amt = money2(it.amount) * (Number(it.quantity) || 1);
        const fee = !isAddOn(name);
        const emp = String(it.creditTo || it.employeeID || '').trim();
        const prof = emp ? profByEmp.get(emp) : null;
        let value = money2(amt * n);
        if (fee && !feeSeen && initExtra > 0) { value = money2(value + initExtra); feeSeen = true; }
        lines.push({ name, kind: fee ? 'fee' : 'addon', per_service: money2(amt), value, credited_employee_id: emp || null, credited_profile_id: prof ? prof.id : null });
      }
      if (!feeSeen && initExtra > 0) lines.push({ name: 'Initial extras', kind: 'fee', per_service: 0, value: initExtra, credited_employee_id: null, credited_profile_id: null });
      const samePerson = (l) => (soldProf && l.credited_profile_id && l.credited_profile_id === soldProf.id) || (!!soldBy && l.credited_employee_id === soldBy);
      const sum = (f) => money2(lines.filter(f).reduce((t, l) => t + l.value, 0));
      const base_value = sum(l => l.kind === 'base'), fee_value = sum(l => l.kind === 'fee');
      const addon_own_value = sum(l => l.kind === 'addon' && samePerson(l)), addon_other_value = sum(l => l.kind === 'addon' && !samePerson(l));
      revRows.push({ subscription_id: String(x.subscriptionID), customer_id: String(x.customerID || rt.customerID || ''), base_service: x.serviceType || null,
        sold_by_employee_id: soldBy || null, sold_by_profile_id: soldProf ? soldProf.id : null, contract_value: cv, recurring_services: n,
        base_value, fee_value, addon_own_value, addon_other_value, commissionable_value: money2(base_value + addon_own_value), lines, active: true, updated_at: nowIso,
        // Service fees are never credited to anyone (per Isaac) — flag any that are, for Auditing.
        fee_credited_count: lines.filter(l => l.kind === 'fee' && l.credited_employee_id).length,
        fee_credited_employee_ids: [...new Set(lines.filter(l => l.kind === 'fee' && l.credited_employee_id).map(l => l.credited_employee_id))] });
    }
    log.revenueRows = 0;
    for (const part of chunk(revRows, 500)) {
      const { error } = await supabase.from('subscription_revenue').upsert(part, { onConflict: 'subscription_id' });
      if (error) { console.warn('[fr-addons] subscription_revenue upsert failed:', error.message); break; }
      log.revenueRows += part.length;
    }

    // 6c. ONE row per rep per account (per Isaac, Sep 29). The base plan and
    //     every add-on credited to the SAME person are one sales row: its
    //     revenue_amount becomes the commissionable piece (base + their own
    //     add-ons; never service fees, never add-ons credited to someone
    //     else). An add-on credited to a different user (office staff or a
    //     technician adding it later) becomes that user's own upsell row.
    //     Only rows not yet paid out are touched.
    const baseSale = new Map();
    for (const part of chunk(revRows.map(r => r.subscription_id), 500)) {
      const { data } = await supabase.from('sales').select('id, crm_subscription_id, rep_id, revenue_amount, sold_date, payroll_processed_at, total_revenue, addon_names')
        .in('crm_subscription_id', part).eq('sale_kind', 'sale');
      (data || []).forEach(r => { if (!baseSale.has(String(r.crm_subscription_id))) baseSale.set(String(r.crm_subscription_id), r); });
    }
    const lineValue = new Map();
    log.baseFolded = 0;
    for (const r of revRows) {
      for (const l of r.lines) if (l.kind === 'addon') lineValue.set(r.subscription_id + '|' + l.name.toLowerCase(), l.value);
      const b = baseSale.get(r.subscription_id); if (!b) continue;
      const own = r.lines.filter(l => l.kind === 'addon' && ((l.credited_profile_id && l.credited_profile_id === b.rep_id) || (!l.credited_profile_id && l.credited_employee_id && l.credited_employee_id === r.sold_by_employee_id)));
      const commissionable = money2(r.base_value + own.reduce((t, l) => t + l.value, 0));
      const names = own.map(l => l.name).join(' + ') || null;
      if (b.payroll_processed_at || String(b.sold_date || '') < String(AL.start).slice(0, 10)) continue;
      if (Math.abs((Number(b.revenue_amount) || 0) - commissionable) < 0.01 && Math.abs((Number(b.total_revenue) || 0) - r.contract_value) < 0.01 && (b.addon_names || null) === names) continue;
      const { error } = await supabase.from('sales').update({ revenue_amount: commissionable, total_revenue: r.contract_value, addon_names: names, commission_split: r.lines, updated_at: nowIso }).eq('id', b.id);
      if (error) console.warn('[fr-addons] base sale split failed', b.id, error.message); else log.baseFolded++;
    }

    // 5. Upsert add_ons (existing rows keep their streak fields; only the
    //    descriptive columns refresh).
    const keys = [...new Set([...addOns.map(a => a.subscription_id), ...Object.keys(subs)])];
    const have = [];
    for (const part of chunk(keys, 500)) { const { data } = await supabase.from('add_ons').select('id, subscription_id, service_name, sale_id, removed_at').in('subscription_id', part); (data || []).forEach(r => have.push(r)); }
    const haveBy = new Map((have || []).map(r => [r.subscription_id + '|' + String(r.service_name).toLowerCase(), r]));
    const now = new Date().toISOString();
    for (const a of addOns) {
      const prof = a.credited_employee_id ? profByEmp.get(String(a.credited_employee_id)) : null;
      if (a.credited_employee_id && !prof) log.unmatchedEmployees++;
      const typeLabel = typeOfEmp.get(String(a.credited_employee_id || '')) || '';
      const row = { ...a, credited_profile_id: prof ? prof.id : null,
        credited_role: /tech/i.test(typeLabel) ? 'technician' : /office/i.test(typeLabel) ? 'office_staff' : /sales/i.test(typeLabel) ? 'sales_rep' : (ROLE_OF_TYPE[typeLabel] || null),
        updated_at: now, last_seen_at: now };
      const ex = haveBy.get(a.subscription_id + '|' + a.service_name.toLowerCase());
      if (ex) {
        if (ex.removed_at) { row.removed_at = null; row.removed_reason = null; }   // put back on the ticket
        const bx = baseSale.get(a.subscription_id);
        if (bx && prof && prof.id === bx.rep_id && !bx.payroll_processed_at && ex.sale_id !== bx.id) {
          // Same person as the base plan → it lives on the base row; remove the separate upsell row this worker made, if unpaid.
          if (ex.sale_id) await supabase.from('sales').delete().eq('id', ex.sale_id).eq('add_on_id', ex.id).is('payroll_processed_at', null);
          row.sale_id = bx.id;
        }
        const { error } = await supabase.from('add_ons').update(row).eq('id', ex.id);
        if (error) console.warn('[fr-addons] update failed', ex.id, error.message); else log.updated++;
        continue;
      }
      const { data: ins, error } = await supabase.from('add_ons').insert({ ...row, created_at: now }).select('id').single();
      if (error) { console.warn('[fr-addons] insert failed', a.subscription_id, a.service_name, error.message); continue; }
      log.inserted++;
      // 6. Automatic upsells: one `sales` row per add-on, attributed to the credited employee.
      // Only add-ons created on/after the autolog start become upsell sales — the
      // nightly full sweep also records every older line already on a recurring
      // ticket, and those must not flood the queues as new sales.
      const bx = baseSale.get(a.subscription_id);
      if (bx && prof && prof.id === bx.rep_id && !bx.payroll_processed_at) {
        // Same rep as the base plan → folded into the base sale row (6c), no separate upsell.
        await supabase.from('add_ons').update({ sale_id: bx.id }).eq('id', ins.id);
        continue;
      }
      if (AL.upsells !== 'off' && prof && String(a.added_at || '') >= String(AL.start).slice(0, 10)) {   // upsells are always automatic (per Isaac, Sep 23) — the manual Log Sale path is retired
        const t = tickets[a.initial_ticket_id || a.first_recurring_ticket_id] || {};
        const sale = upsellSaleRow({
          ticket_id: 'addon:' + ins.id, customer_id: a.customer_id, subscription_id: a.subscription_id, office_id: a.office_fr_id,
          first_name: t.firstName || '', last_name: t.lastName || '', created: a.added_at, created_by: a.credited_employee_id,
          created_by_type: row.credited_role === 'technician' ? '1' : row.credited_role === 'sales_rep' ? '2' : '0',
          service: a.service_name, total: lineValue.get(a.subscription_id + '|' + a.service_name.toLowerCase()) ?? (a.initial_amount + a.recurring_amount),
        }, { repId: prof.id, officeId: officeByFr.get(String(a.office_fr_id)) ?? prof.office_id ?? null, serviceTypeId: svcByName.get(a.service_name.toLowerCase()) || null, now });
        // Revenue = the add-on's per-service charge × the services left on the contract (6b), falling back to one charge.
        sale.add_on_id = ins.id;
        const { data: s, error: se } = await supabase.from('sales').insert(sale).select('id').single();
        if (se) console.warn('[fr-addons] sale insert failed', ins.id, se.message);
        else { log.sales++; await supabase.from('add_ons').update({ sale_id: s.id }).eq('id', ins.id); }
      }
    }
    // 7. Removals. Any open add-on on a subscription we just read whose line
    //    is no longer on the recurring ticket was removed today; on the
    //    nightly full sweep, open add-ons on subscriptions that are no
    //    longer active end on the subscription's cancel date.
    const today = now.slice(0, 10);
    const present = new Set(addOns.map(a => a.subscription_id + '|' + a.service_name.toLowerCase()));
    log.removed = 0;
    for (const r of have) {
      if (r.removed_at) continue;
      const k = r.subscription_id + '|' + String(r.service_name).toLowerCase();
      if (subs[r.subscription_id] && !present.has(k)) {
        await supabase.from('add_ons').update({ removed_at: today, removed_reason: 'item_removed', updated_at: now }).eq('id', r.id); log.removed++;
      }
    }
    if (full) {
      const { data: open } = await supabase.from('add_ons').select('id, subscription_id').is('removed_at', null);
      const gone = (open || []).filter(r => !subs[r.subscription_id]);
      const goneSubs = [...new Set(gone.map(r => r.subscription_id))];
      const info = {};
      for (const part of chunk(goneSubs, 1000)) { try { const got = await fr('subscription/get', { subscriptionIDs: part.map(Number) }); listOf(got, 'subscriptions').forEach(x => { info[String(x.subscriptionID)] = x; }); } catch (e) { console.warn('[fr-addons] cancel lookup failed', e.message); } }
      for (const r of gone) {
        const x = info[r.subscription_id]; if (!x) continue;   // unknown → leave it open rather than guess
        const cx = String(x.dateCancelled || '').slice(0, 10);
        await supabase.from('add_ons').update({ removed_at: /^\d{4}-\d{2}-\d{2}$/.test(cx) && !cx.startsWith('0000') ? cx : today, removed_reason: 'subscription_cancelled', updated_at: now }).eq('id', r.id); log.removed++;
      }
    }
    console.log('[fr-addons] done', JSON.stringify({ ...log, from, ms: Date.now() - started }));
    return { statusCode: 200, body: JSON.stringify({ ...log, from, ms: Date.now() - started }) };
  } catch (e) {
    console.error('[fr-addons] failed', e);
    return { statusCode: 500, body: 'fr-addons failed: ' + (e.message || e) };
  }
};
