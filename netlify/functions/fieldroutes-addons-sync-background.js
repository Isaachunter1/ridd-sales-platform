    (rosterQ.data || []).forEach(e => { const nm = [String(e.lname || '').trim(), String(e.fname || '').trim()].filter(Boolean).join(', '); if (nm) String(e.employee_ids || e.employee_id || '').split(',').map(x => x.trim()).filter(Boolean).forEach(id => nameOfEmpA.set(id, nm)); });
