// ── FieldRoutes ticket items → add_ons (per Isaac + COO, Sep 2026) ──────────
// SKELETON. RIDD is moving to < 25 service types with everything else sold
// as an ADD-ON: a ticket item on the invoice, credited (per line) to the
// employee who sold it. RevHawk does not mirror ticket items
// (FieldRoutesTicket.fieldRoutes_items is empty on every row), so this
// worker asks the FieldRoutes API directly — the same way the live pull
// asks for subscriptions — and writes one add_ons row per
// (subscription, add-on service), folding the initial and recurring
// charges of the same add-on into one row (netlify/lib/add-on-streak.js).
//
// With app_settings.autolog.upsells === 'auto' it also creates the `sales`
// upsell row (netlify/lib/upsell-record.js) so the Technicians / Office
// Sales tabs show the add-on the same day; with 'manual' it only records the
// add-on (the Log Sale form stays).
//
// Runs every 15 min in selling hours (addons-scheduled.js). Idempotent: the
// unique (subscription_id, service_name) key and sales.crm_ticket_id dedupe.
//
// TODO(Isaac) before this goes live — confirm against the dummy account
// [68003] / sub 193894 recurring ticket:
//   • ticketItem endpoints: assumed `ticketItem/search` (dateCreated ≥ from,
//     returns ticketItemIDs) and `ticketItem/get` (ticketItemIDs → items).
//   • item field names read in add-on-streak.js normalizeItem(): ticketItemID,
//     ticketID, description, total, employeeID (credit-to), dateCreated.
//   • which ticket field marks the initial ticket (autoGeneratedType / templateType).
//
// Env: FIELDROUTES_SUBDOMAIN / FIELDROUTES_AUTH_KEY / FIELDROUTES_AUTH_TOKEN,
//      SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY. Silently skips without them.

const { createClient } = require('@supabase/supabase-js');
const { requireSyncSecret } = require('../lib/sync-gate.js');
const { makeIsAddOn, upsellSaleRow } = require('../lib/upsell-record.js');
const { groupTicketItems } = require('../lib/add-on-streak.js');

function frBase() { const sub = (process.env.FIELDROUTES_SUBDOMAIN || '').trim(); return sub ? 'https://' + sub + '.pestroutes.com/api/' : null; }
async function fr(endpoint, params) {
  const q = new URLSearchParams({ authenticationKey: process.env.FIELDROUTES_AUTH_KEY || '', authenticationToken: process.env.FIELDROUTES_AUTH_TOKEN || '' });
  for (const [k, v] of Object.entries(params || {})) q.set(k, typeof v === 'string' ? v : JSON.stringify(v));
  let res, txt;
  for (let attempt = 0; ; attempt++) {
    res = await fetch(frBase() + endpoint + '?' + q.toString()); txt = await res.text();
    const limited = res.status === 429 || /too many requests|rate limit/i.test(txt.slice(0, 300));
    if (!limited || attempt >= 2) break;
    await new Promise(r => setTimeout(r, 1500 * (attempt + 1)));
  }
  let json; try { json = JSON.parse(txt); } catch (e) { throw new Error(endpoint + ': non-JSON (' + res.status + '): ' + txt.slice(0, 120)); }
  if (json.success === false || (json.errorMessage && json.errorMessage !== '')) throw new Error(endpoint + ': ' + (json.errorMessage || 'request failed'));
  return json;
}
const chunk = (arr, n) => { const out = []; for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n)); return out; };
const listOf = (got, key) => Array.isArray(got[key]) ? got[key] : Object.values(got[key] || {});
const ROLE_OF_TYPE = { '0': 'office_staff', '1': 'technician', '2': 'sales_rep' };

exports.handler = async (event) => {
  const started = Date.now();
  const _gate = requireSyncSecret(event); if (_gate) return _gate;
  const SUPABASE_URL = process.env.SUPABASE_URL, SERVICE_ROLE = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!SUPABASE_URL || !SERVICE_ROLE) return { statusCode: 500, body: 'SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY required' };
  if (!frBase() || !process.env.FIELDROUTES_AUTH_KEY || !process.env.FIELDROUTES_AUTH_TOKEN) return { statusCode: 200, body: 'fieldroutes env not set — skipped' };
  const supabase = createClient(SUPABASE_URL, SERVICE_ROLE, { auth: { persistSession: false } });
  const log = { items: 0, addOns: 0, inserted: 0, updated: 0, sales: 0, unmatchedEmployees: 0 };
  try {
    const { data: alRow } = await supabase.from('app_settings').select('value').eq('key', 'autolog').maybeSingle();
    const AL = Object.assign({ enabled: false, start: '2026-01-01', upsells: 'manual', upsell_services: [], addons_lookback_days: 3 }, (alRow && alRow.value) || {});
    if (!AL.enabled) return { statusCode: 200, body: 'autolog disabled — skipped' };
    const isAddOn = makeIsAddOn(AL.upsell_services);
    const lookback = Math.max(1, Number(AL.addons_lookback_days) || 3);
    const since = new Date(Date.now() - lookback * 86400000).toISOString().slice(0, 10);
    const from = since > String(AL.start).slice(0, 10) ? since : String(AL.start).slice(0, 10);

    // 1. Ticket items added since `from`.
    const search = await fr('ticketItem/search', { dateCreated: { operator: '>=', value: from } });
    const ids = (search.ticketItemIDs || search.itemIDs || []).map(String);
    if (!ids.length) return { statusCode: 200, body: 'no new ticket items' };
    const items = [];
    for (const part of chunk(ids, 1000)) { const got = await fr('ticketItem/get', { ticketItemIDs: part.map(Number) }); items.push(...listOf(got, 'ticketItems')); }
    log.items = items.length;

    // 2. Their tickets (subscription / customer / initial-vs-recurring live there).
    const ticketIds = [...new Set(items.map(i => String(i.ticketID || '')).filter(Boolean))];
    const tickets = {};
    for (const part of chunk(ticketIds, 1000)) { const got = await fr('ticket/get', { ticketIDs: part.map(Number) }); listOf(got, 'tickets').forEach(t => { tickets[String(t.ticketID)] = t; }); }

    // 3. Fold into add-ons.
    const addOns = groupTicketItems(items, { isAddOn, tickets });
    log.addOns = addOns.length;
    if (!addOns.length) return { statusCode: 200, body: JSON.stringify({ ...log, ms: Date.now() - started }) };

    // 4. Resolve the credited employee → app profile (any of a person's branch ids).
    const [rosterQ, profQ, offQ, svcQ] = await Promise.all([
      supabase.from('fieldroutes_employees').select('employee_id, employee_ids, type_label, type'),
      supabase.from('profiles').select('id, fieldroutes_employee_id, office_id').not('fieldroutes_employee_id', 'is', null),
      supabase.from('offices').select('id, name'),
      supabase.from('service_types').select('id, name'),
    ]);
    const profByEmp = new Map(); const typeOfEmp = new Map();
    (profQ.data || []).forEach(p => profByEmp.set(String(p.fieldroutes_employee_id).trim(), p));
    (rosterQ.data || []).forEach(e => {
      const all = String(e.employee_ids || e.employee_id || '').split(',').map(x => x.trim()).filter(Boolean);
      const hit = all.map(id => profByEmp.get(id)).find(Boolean);
      all.forEach(id => { if (hit && !profByEmp.has(id)) profByEmp.set(id, hit); typeOfEmp.set(id, e.type_label || e.type || null); });
    });
    // FieldRoutes officeID → app office id, by name (same as the live pull).
    const officeByFr = new Map(); const officeByName = new Map((offQ.data || []).map(o => [String(o.name || '').trim().toLowerCase(), o.id]));
    try { const got = await fr('office/get', {}); listOf(got, 'offices').forEach(o => { const id = officeByName.get(String(o.officeName || '').trim().toLowerCase()); if (id) officeByFr.set(String(o.officeID), id); }); } catch (e) { console.warn('[fr-addons] office lookup skipped:', e.message); }
    const svcByName = new Map((svcQ.data || []).map(s => [String(s.name || '').trim().toLowerCase(), s.id]));

    // 5. Upsert add_ons (existing rows keep their streak fields; only the
    //    descriptive columns refresh).
    const keys = addOns.map(a => a.subscription_id);
    const { data: have } = await supabase.from('add_ons').select('id, subscription_id, service_name, sale_id').in('subscription_id', keys);
    const haveBy = new Map((have || []).map(r => [r.subscription_id + '|' + String(r.service_name).toLowerCase(), r]));
    const now = new Date().toISOString();
    for (const a of addOns) {
      const prof = a.credited_employee_id ? profByEmp.get(String(a.credited_employee_id)) : null;
      if (a.credited_employee_id && !prof) log.unmatchedEmployees++;
      const typeLabel = typeOfEmp.get(String(a.credited_employee_id || '')) || '';
      const row = { ...a, credited_profile_id: prof ? prof.id : null,
        credited_role: /tech/i.test(typeLabel) ? 'technician' : /office/i.test(typeLabel) ? 'office_staff' : /sales/i.test(typeLabel) ? 'sales_rep' : (ROLE_OF_TYPE[typeLabel] || null),
        updated_at: now };
      const ex = haveBy.get(a.subscription_id + '|' + a.service_name.toLowerCase());
      if (ex) {
        const { error } = await supabase.from('add_ons').update(row).eq('id', ex.id);
        if (error) console.warn('[fr-addons] update failed', ex.id, error.message); else log.updated++;
        continue;
      }
      const { data: ins, error } = await supabase.from('add_ons').insert({ ...row, created_at: now }).select('id').single();
      if (error) { console.warn('[fr-addons] insert failed', a.subscription_id, a.service_name, error.message); continue; }
      log.inserted++;
      // 6. Automatic upsells: one `sales` row per add-on, attributed to the credited employee.
      if (AL.upsells === 'auto' && prof) {
        const t = tickets[a.initial_ticket_id || a.first_recurring_ticket_id] || {};
        const sale = upsellSaleRow({
          ticket_id: 'addon:' + ins.id, customer_id: a.customer_id, subscription_id: a.subscription_id, office_id: a.office_fr_id,
          first_name: t.firstName || '', last_name: t.lastName || '', created: a.added_at, created_by: a.credited_employee_id,
          created_by_type: row.credited_role === 'technician' ? '1' : row.credited_role === 'sales_rep' ? '2' : '0',
          service: a.service_name, total: a.initial_amount + a.recurring_amount,
        }, { repId: prof.id, officeId: officeByFr.get(String(a.office_fr_id)) ?? prof.office_id ?? null, serviceTypeId: svcByName.get(a.service_name.toLowerCase()) || null, now });
        // TODO(pay rules): contract value for an add-on = initial + recurring × remaining services on the parent subscription; the sync
        // only knows the two charges today, so revenue_amount is their sum until the reconcile worker prices it.
        sale.add_on_id = ins.id;
        const { data: s, error: se } = await supabase.from('sales').insert(sale).select('id').single();
        if (se) console.warn('[fr-addons] sale insert failed', ins.id, se.message);
        else { log.sales++; await supabase.from('add_ons').update({ sale_id: s.id }).eq('id', ins.id); }
      }
    }
    console.log('[fr-addons] done', JSON.stringify({ ...log, from, ms: Date.now() - started }));
    return { statusCode: 200, body: JSON.stringify({ ...log, from, ms: Date.now() - started }) };
  } catch (e) {
    console.error('[fr-addons] failed', e);
    return { statusCode: 500, body: 'fr-addons failed: ' + (e.message || e) };
  }
};
