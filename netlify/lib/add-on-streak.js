'use strict';
// ════════════════════════════════════════════════════════════════════════
// ADD-ON STREAK (per Isaac + COO, Sep 2026) — pure, no I/O. The one place
// that decides where an add-on stands on its way to backend pay:
//
//   groupTicketItems(items)     FieldRoutes ticket items ──▶ one add-on per
//                               (subscription, add-on service), initial and
//                               recurring charges folded together.
//   streakOf(addOn, invoices)   tickets (= invoices) since the add-on date
//                               ──▶ { paid, status, qualifying, brokeAt, reason }
//
// Rules (COO):
//   • Counting starts ON or after the add-on date (a customer can pay an
//     initial fee for the add-on the same day; that invoice counts).
//   • Only PAID invoices count (balance 0 / an applied payment).
//   • The add-on must STILL be on each counted invoice — an invoice without
//     the item is a break, not a skip.
//   • 5 in a row → locked (backend payable next quarterly run).
//   • Subscription cancelled before 5 → broken. Streak breaks AFTER a payout
//     → clawback (the pay run stamps that; this file only reports 'broken').
// tools/addon-test.js pins these with fixtures.
// ════════════════════════════════════════════════════════════════════════

const LOCK_AT = 5;
const norm = (x) => String(x || '').trim().toLowerCase();
const day = (x) => String(x || '').slice(0, 10);
const money = (x) => Math.round((Number(x) || 0) * 100) / 100;

// A ticket item as the FieldRoutes `ticketItem` endpoint returns it. Field
// names are read defensively — TODO(Isaac): confirm against the dummy
// account [68003] recurring ticket once the endpoint is wired up.
function normalizeItem(it, tickets) {
  const t = tickets && tickets[String(it.ticketID || it.ticket_id || '')];
  return {
    itemId: String(it.ticketItemID || it.itemID || it.id || ''),
    ticketId: String(it.ticketID || it.ticket_id || ''),
    customerId: String(it.customerID || (t && t.customerID) || ''),
    subscriptionId: String(it.subscriptionID || (t && t.subscriptionID) || ''),
    officeId: String(it.officeID || (t && t.officeID) || ''),
    serviceId: String(it.serviceID || it.productID || ''),
    name: String(it.description || it.serviceDescription || it.productDescription || it.name || '').trim(),
    employeeId: String(it.employeeID || it.creditTo || it.soldBy || it.createdBy || '').trim(),
    amount: money(it.total ?? it.amount ?? it.price ?? it.unitPrice ?? 0),
    date: day(it.dateCreated || it.date || (t && (t.invoiceDate || t.dateCreated)) || ''),
    isInitial: !!(t && (String(t.autoGeneratedType || '').toLowerCase().includes('initial') || String(t.templateType || '') === 'INITIAL')),
  };
}

// Fold items into add-ons keyed by subscription + service name. The initial
// ticket's charge and the recurring charge are the SAME add-on (Isaac: "they
// mesh into a single add-on, we just charge separately").
function groupTicketItems(items, opts) {
  const isAddOn = (opts && opts.isAddOn) || (() => true);
  const tickets = (opts && opts.tickets) || {};
  const map = new Map();
  for (const raw of items || []) {
    if (!raw || typeof raw !== 'object') continue;
    const it = normalizeItem(raw, tickets);
    if (!it.subscriptionId || !it.name || !isAddOn(it.name)) continue;
    const key = it.subscriptionId + '|' + norm(it.name);
    let a = map.get(key);
    if (!a) {
      a = { subscription_id: it.subscriptionId, customer_id: it.customerId, office_fr_id: it.officeId || null, service_id: it.serviceId || null, service_name: it.name,
            credited_employee_id: it.employeeId || null, added_at: it.date || null, initial_amount: 0, recurring_amount: 0,
            initial_ticket_id: null, first_recurring_ticket_id: null, item_ids: [] };
      map.set(key, a);
    }
    if (it.itemId && !a.item_ids.includes(it.itemId)) a.item_ids.push(it.itemId);
    if (it.date && (!a.added_at || it.date < a.added_at)) a.added_at = it.date;
    if (!a.credited_employee_id && it.employeeId) a.credited_employee_id = it.employeeId;
    if (it.isInitial) { a.initial_amount = money(a.initial_amount + it.amount); if (!a.initial_ticket_id) a.initial_ticket_id = it.ticketId; }
    else { if (!a.first_recurring_ticket_id) { a.first_recurring_ticket_id = it.ticketId; a.recurring_amount = it.amount; } }
  }
  return [...map.values()];
}

// invoices: [{ ticket_id, invoice_date, paid (bool), paid_at?, amount, has_add_on (bool|null), active (bool) }]
// null has_add_on = "unknown" (RevHawk has no items yet) — treated as present
// so the count can advance; the reconcile worker fills it in when it can.
function streakOf(addOn, invoices, opts) {
  const lockAt = (opts && opts.lockAt) || LOCK_AT;
  const from = day(addOn.added_at);
  const rows = (invoices || [])
    .filter(i => i && day(i.invoice_date) >= from && i.active !== false)
    .sort((a, b) => day(a.invoice_date) < day(b.invoice_date) ? -1 : day(a.invoice_date) > day(b.invoice_date) ? 1 : 0);
  const qualifying = [];
  for (const inv of rows) {
    if (inv.has_add_on === false) return { paid: qualifying.length, status: 'broken', qualifying, brokeAt: day(inv.invoice_date), reason: 'item_removed' };
    if (!inv.paid) continue;                       // unpaid invoices wait; they neither count nor break
    qualifying.push({ ticket_id: String(inv.ticket_id), invoice_date: day(inv.invoice_date), paid_at: inv.paid_at ? day(inv.paid_at) : null, amount: money(inv.amount), has_add_on: inv.has_add_on !== false });
    if (qualifying.length >= lockAt) return { paid: qualifying.length, status: 'locked', qualifying, lockedAt: qualifying[qualifying.length - 1].paid_at || qualifying[qualifying.length - 1].invoice_date };
  }
  if (addOn.subscription_active === false) return { paid: qualifying.length, status: 'broken', qualifying, brokeAt: day(addOn.subscription_cancelled_at) || null, reason: 'subscription_cancelled' };
  return { paid: qualifying.length, status: 'accruing', qualifying };
}

module.exports = { LOCK_AT, normalizeItem, groupTicketItems, streakOf };
